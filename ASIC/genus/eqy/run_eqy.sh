#!/bin/bash
# Open-source logic equivalence check (RTL vs Genus netlist) using Yosys EQY.
# Replaces Conformal LEC, which we don't have.
#
# Usage:   bash run_eqy.sh <design> [top_module]
# Example: bash run_eqy.sh gpio
#
# Needs OSS CAD Suite on PATH (yosys, eqy, sby, yices and the slang plugin):
#   source /tapeout/lec_tool/oss-cad-suite/environment
#
# Reads the same filelist Genus used (filelists/<design>.f) as the golden
# design and out/<design>/<design>_netlist.v as the gate design.
# Results go to eqy/work/<design>/.

set -e

DESIGN=${1:-gpio}
EQY_DIR=$(cd "$(dirname "$0")" && pwd)
GENUS_DIR=$(cd "$EQY_DIR/.." && pwd)
REPO_ROOT=$(cd "$GENUS_DIR/../.." && pwd)
TOP=${2:-${DESIGN}_synth_top}

# Same standard-cell library Genus used (see config.tcl). Override with STD_LIB=...
STD_LIB=${STD_LIB:-/opt/open_pdks/sky130/sky130A/libs.ref/sky130_fd_sc_hd/lib/sky130_fd_sc_hd__tt_025C_1v80.lib}

FILELIST=$GENUS_DIR/filelists/$DESIGN.f
NETLIST=$GENUS_DIR/out/$DESIGN/${DESIGN}_netlist.v
WORK_DIR=$EQY_DIR/work

for f in "$FILELIST" "$NETLIST" "$STD_LIB"; do
    if [ ! -f "$f" ]; then
        echo "ERROR: missing $f" >&2
        exit 1
    fi
done
command -v eqy >/dev/null || { echo "ERROR: eqy not on PATH (source oss-cad-suite/environment)" >&2; exit 1; }

# Filelist -> absolute paths (skip comments/blank lines, strip CRLF)
RTL_FILES=$(tr -d '\r' < "$FILELIST" | grep -v '^[[:space:]]*#' | grep -v '^[[:space:]]*$' \
            | sed "s|^[[:space:]]*|$REPO_ROOT/|" | tr '\n' ' ')

mkdir -p "$WORK_DIR"
EQY_FILE=$WORK_DIR/$DESIGN.eqy

cat > "$EQY_FILE" <<EOF
# Generated by run_eqy.sh - do not edit, edit the script instead.

# Golden: RTL, read with the slang SystemVerilog frontend (handles interfaces)
[gold]
plugin -i slang
read_slang -I $REPO_ROOT/RTL/memory --top $TOP $RTL_FILES
prep -flatten -top $TOP

# Gate: Genus netlist. read_liberty WITHOUT -lib so cells get real logic
# from their 'function' attributes (with -lib they'd be black boxes).
[gate]
read_liberty -ignore_miss_func $STD_LIB
read_verilog $NETLIST
prep -flatten -top $TOP

[strategy sby]
use sby
depth 10
engine smtbmc yices
EOF

cd "$WORK_DIR"
eqy -f -d "$DESIGN" "$EQY_FILE"
